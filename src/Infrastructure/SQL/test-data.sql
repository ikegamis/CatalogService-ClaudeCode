-- ■ ユースケース別の確認方法
--   UC-BOOK-001 書籍登録
--     正常: 未登録の書籍ID 9784000000099 を登録する
--     異常: 登録済みの 9784000000001 を登録する → BOOK_ALREADY_EXISTS
--           13文字でない書籍ID、空のタイトル、価格 0 / 1000001 / 小数 → VALIDATION_ERROR
--   UC-REVIEW-001 レビュー登録
--     正常: 書籍 9784000000001 にレビューを登録する。name / comment を省略すると「名無し」/ コメントなし
--     異常: 未登録の書籍ID 9784999999999 を指定する → BOOK_NOT_FOUND
--           rating 0 / 6 / 小数、51文字の name → VALIDATION_ERROR
--   UC-REVIEW-002 レビュー更新
--     正常: 01JD0000000000000000000006 を更新する（書籍IDを未登録の 9784999999999 にしても成功する。書籍の存在は確認しない）
--     異常: 未登録の 01JD00000000000000000000ZZ を指定する → REVIEW_NOT_FOUND
--           ULID 形式でないレビューID → VALIDATION_ERROR
--   UC-CATALOG-003 レビュー削除
--     正常: 01JD0000000000000000000007 を削除する
--     異常: 未登録の 01JD00000000000000000000ZZ を指定する → REVIEW_NOT_FOUND
--   UC-CATALOG-001 書籍推薦
--     9784000000001・threshold 省略（0.6）→ ["オブジェクト指向入門", "リファクタリング"]
--     9784000000001・threshold 0          → ["オブジェクト指向入門", "リファクタリング", "テスト駆動開発"]
--                                           （後ろ2冊は言及回数・言及レビュー数が同じ。品質係数の高いレビュー 01 で言及された方が先）
--     9784000000001・threshold 1          → []（信頼性スコアが 1.0 のレビューがない）
--     9784000000003（レビューなし）        → []
--     9784999999999（未登録の書籍）        → []
--     threshold -0.1 / 1.1               → VALIDATION_ERROR
-- =============================================================================

INSERT INTO book (book_id, title, author, price) VALUES
    -- 推薦の対象書籍。レビュー 01〜05 が紐づく
    ('9784000000001', 'ドメイン駆動設計入門', '山田太郎', 3200),
    -- レビューの中で前提書籍として言及される書籍。レビュー 06・07 が紐づく
    ('9784000000002', 'オブジェクト指向入門', '佐藤花子', 2800),
    -- レビューのない書籍
    ('9784000000003', 'TypeScript入門', '鈴木一郎', 2500),
    -- 境界値（最小）: タイトル・著者 1 文字、価格 1 円
    ('9784000000004', 'A', 'B', 1),
    -- 境界値（最大）: 価格 1,000,000 円
    ('9784000000005', '高額な専門書', '高橋次郎', 1000000)
ON CONFLICT (book_id) DO NOTHING;

